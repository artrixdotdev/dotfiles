vim.api.nvim_create_autocmd("ColorScheme", {
   group = vim.api.nvim_create_augroup("UserThemeHighlights", { clear = true }),
   callback = function(event)
      if event.match == "dms" then
         apply_theme_highlights()
      end
   end,
})

